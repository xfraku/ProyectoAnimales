-- PetSkin AI: ejecutar UNA VEZ en una base NUEVA llamada petskin_db.
-- Compatible con los nombres utilizados en app.py; no importa datos antiguos.
-- No contiene DROP ni modifica tablas existentes. Un error revierte la transaccion.
-- DECISIONES: usuario eliminado => elimina sus mascotas, consultas y mensajes.
-- Mascota eliminada => conserva consultas, desvinculando mascota_id.
-- Consulta eliminada => elimina sus mensajes. S3 NO se elimina mediante SQL.
-- Se admite especialista para el cambio de interfaz acordado, aun no implementado.
BEGIN;

DO $$ BEGIN
    IF current_database() <> 'petskin_db' THEN
        RAISE EXCEPTION 'Conectate a petskin_db antes de ejecutar este script';
    END IF;
END $$;

CREATE TABLE public.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL CHECK (btrim(username) <> ''),
    email VARCHAR(100) NOT NULL CHECK (btrim(email) <> ''),
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'admin', 'especialista'))
);
CREATE UNIQUE INDEX users_username_unique ON public.users (lower(btrim(username)));
CREATE UNIQUE INDEX users_email_unique ON public.users (lower(btrim(email)));

CREATE TABLE public.mascotas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    nombre VARCHAR(100) NOT NULL,
    raza VARCHAR(100) NOT NULL,
    peso DOUBLE PRECISION NOT NULL,
    tamano VARCHAR(50) NOT NULL,
    historial TEXT,
    fecha_registro TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'America/Lima')
);

CREATE TABLE public.conversations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    -- El flujo actual crea la consulta antes de vincular una mascota.
    mascota_id INTEGER REFERENCES public.mascotas(id) ON DELETE SET NULL,
    diagnostico_ml VARCHAR(100) NOT NULL,
    confianza_ml DOUBLE PRECISION NOT NULL,
    imagen_path VARCHAR(255) NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'America/Lima')
);

CREATE TABLE public.chat_messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id INTEGER NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
    role VARCHAR(50) NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'America/Lima')
);

CREATE INDEX mascotas_user_id_idx ON public.mascotas(user_id);
CREATE INDEX conversations_user_fecha_idx ON public.conversations(user_id, fecha DESC);
CREATE INDEX conversations_mascota_id_idx ON public.conversations(mascota_id);
CREATE INDEX chat_messages_conversation_id_idx ON public.chat_messages(conversation_id, id);
COMMIT;

SELECT table_name FROM information_schema.tables
WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
ORDER BY table_name;
