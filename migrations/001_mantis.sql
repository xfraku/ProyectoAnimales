-- La fotografía de los datos históricos no se puede reconstruir con exactitud:
-- se señala expresamente que se obtuvo de los datos actuales al migrar.
UPDATE conversations c SET patient_snapshot = jsonb_build_object(
  'nombre', m.nombre, 'raza', m.raza, 'peso', m.peso, 'tamano', m.tamano,
  'historial', coalesce(m.historial,''), 'color', m.color, 'origen', 'Datos disponibles al migrar')
FROM mascotas m WHERE c.mascota_id = m.id AND c.patient_snapshot IS NULL;

CREATE TABLE IF NOT EXISTS access_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    event VARCHAR(60) NOT NULL,
    ip_address VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS access_events_date_idx ON access_events(created_at DESC);
CREATE TABLE IF NOT EXISTS admin_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    target_id INTEGER,
    action VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS audit_findings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    evidence TEXT NOT NULL,
    recommendation TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS preventive_advice (
